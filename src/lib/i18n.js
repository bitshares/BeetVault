function buildLocale(common, operations, vaulta, bts, wax, tlos, fio, libre, xpr, hive, atomic) {
  return {
    common,
    operations: {
      ...operations,
      injected: {
        VAULTA: vaulta,
        BTS: bts,
        WAX: wax,
        TLOS: tlos,
        FIO: fio,
        LIBRE: libre,
        XPR: xpr,
        HIVE: hive,
        ATOMIC: atomic,
      }
    }
  };
}

